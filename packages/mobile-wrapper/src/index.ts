/**
 * Render the app's quick-start runbook: the durable "read me first" that tells a
 * future dev exactly what to set up (keystore, GH secrets, Obtainium) so they do
 * not have to re-derive the setup (P4.3's core goal).
 */
export function renderRunbook(c: MobileWrapperConfig): string {
  return `# Wrap ${c.appName} for Android (Capacitor + signed-APK CI)

Generated by @calendarx/mobile-wrapper. This is a reusable template — anyone can
wrap a TanStack (or any SSR/SPA) web app as a signed Android APK and publish it
through Obtainium without redoing the setup.

## Shape: ${c.shape === 'monorepo' ? 'monorepo (pnpm + Turborepo)' : 'single npm app'}

- Wrapper package: ${c.wrapperDir} (capacitor.config.ts + committed android/)
- webDir: ${c.webDir}
- appId: ${c.appId}  appName: ${c.appName}
- Baked live origin: \`${c.originEnv}\` (fallback ${c.defaultOrigin})

## Files to land

1. \`${c.wrapperDir}/capacitor.config.ts\` — the rendered Capacitor config.
2. \`${c.wrapperDir}/android/\` — commit the native project (\`npx cap add android\`
   once, then commit it; CI does \`cap sync\` and regenerates build outputs).
3. \`.github/workflows/release-android.yml\` — the rendered signed-APK workflow.
   Triggers on \`v*\` tags + \`workflow_dispatch\`; stages
   \`${c.apkPrefix}-v<ver>.apk\`; mirrors to ${c.publicReleaseRepo}.

## One-time setup (do NOT redo per release)

### 1. Signing keystore (never commit — CI secret only)
\`\`\`
keytool -genkeypair -v -keystore ~/${c.apkPrefix}.keystore -alias ${c.apkPrefix} \\
  -keyalg RSA -keysize 2048 -validity 10000 -dname "CN=${c.appName},OU=Mobile,O=Xeroneon"
\`\`\`

### 2. GitHub Actions secrets on ${c.sourceRepo}
- \`ANDROID_SIGNING_KEYSTORE_BASE64\` — base64 of the keystore
- \`ANDROID_SIGNING_KEYSTORE_PASSWORD\` / \`ANDROID_SIGNING_KEY_ALIAS\` / \`ANDROID_SIGNING_KEY_PASSWORD\`
- \`${c.originEnv}\` — the LIVE origin (e.g. \`${c.defaultOrigin}\`), NOT a dead
  placeholder. Baked at \`cap sync\`; wrong origin = app installs but renders nothing.
- \`RELEASE_REPO_PAT\` — classic PAT with \`repo\` scope to publish to the PUBLIC
  ${c.publicReleaseRepo} from this private source repo. (GITHUB_TOKEN is repo-scoped.)

### 3. Public Obtainium channel ${c.publicReleaseRepo}
- Must be a PUBLIC, release-only repo. Seed it with an initial README on main
  BEFORE the first mirror run, or GitHub 422s 'Repository is empty'.
- Obtainium source = ${c.publicReleaseRepo}, "What to install" regex
  \`${c.apkPrefix}-v[.\\\\\\\\d]+[.]apk\`, Version check = By release TAG NAME.

## Build on a new machine
\`\`\`
npm i  # or pnpm install
# local dev/prod web build first, then:
cd ${c.wrapperDir} && ${c.shape === 'monorepo' ? 'pnpm exec' : 'npx'} cap sync android
cd android && ./gradlew assembleRelease
\`\`\`
Without signing \`-P\` props, gradle falls back to the DEBUG key (still builds, not
the release cert). Verify the baked origin + signer before publishing
(\`python3 scripts/verify_apk_origin.py <apk> [origin]\`).

## CI pitfalls (all hit live; see skill capacitor-android-obtainium-release)
- Snapshots secrets at workflow START — change => re-trigger.
- Mark broken-origin releases prerelease so Obtainium skips them.
- npm lockfile: regenerate with the SAME npm the CI node uses (npm 10 / node 22),
  or \`npm ci\` rejects it (out-of-sync).
- Verify origin resolves (curl it) before trusting an APK.
`
}

export interface FullOutput extends RenderResult {
  runbook: string
}

/** Render config + workflow + runbook for a wrapper config. */
export function renderAll(c: MobileWrapperConfig): FullOutput {
  const r = renderMobileWrapper(c)
  return { ...r, runbook: renderRunbook(c) }
}